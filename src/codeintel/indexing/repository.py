"""Discover indexable source files in a repository."""

from __future__ import annotations

import os
import subprocess
from collections.abc import Iterable, Iterator
from pathlib import Path

from codeintel.schemas import SourceFile

LANGUAGE_BY_EXTENSION = {
    ".py": "python",
    ".pyi": "python",
    ".ts": "typescript",
    ".mts": "typescript",
    ".cts": "typescript",
    ".tsx": "tsx",
    ".js": "javascript",
    ".mjs": "javascript",
    ".cjs": "javascript",
    ".jsx": "javascript",
    ".java": "java",
    ".go": "go",
    ".rs": "rust",
}

DEFAULT_LANGUAGES = frozenset({"python", "typescript", "tsx", "javascript"})

SKIP_DIRS = frozenset(
    {
        ".git", ".hg", ".svn", "node_modules", "bower_components", "__pycache__", ".mypy_cache",
        ".pytest_cache", ".ruff_cache", ".tox", ".nox", ".venv", "venv", "env", ".eggs", "site-packages",
        "dist", "build", "out", "target", "coverage", ".next", ".nuxt", ".turbo", ".cache", "vendor", "_vendor",
        "vendored", "third_party", "thirdparty",
    }
)

MAX_FILE_BYTES = 1_000_000
MAX_LINE_CHARS = 2_000  # longer lines almost always mean minified or generated code


def detect_language(path: str | Path) -> str | None:
    name = str(path)
    if name.endswith(".d.ts"):
        return None  # declaration files duplicate the implementation's surface
    return LANGUAGE_BY_EXTENSION.get(Path(name).suffix.lower())


def _git_files(root: Path) -> list[str] | None:
    """Tracked + untracked-but-not-ignored files, honouring .gitignore. None if not a git checkout."""
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True,
            check=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    return [p for p in out.decode("utf-8", errors="surrogateescape").split("\0") if p]


def _walk_files(root: Path) -> Iterator[str]:
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(filenames):
            yield Path(dirpath, name).relative_to(root).as_posix()


def is_probably_generated(text: str) -> bool:
    head = text[:2_000].lower()
    if "@generated" in head or "do not edit" in head or "autogenerated" in head:
        return True
    return any(len(line) > MAX_LINE_CHARS for line in text.splitlines())


def read_source(path: Path) -> str | None:
    try:
        if path.stat().st_size > MAX_FILE_BYTES:
            return None
        data = path.read_bytes()
    except OSError:
        return None
    return _decode_source(data)


def _decode_source(data: bytes) -> str | None:
    if b"\0" in data[:8192]:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


def _skipped_dir(rel: str) -> bool:
    return any(p in SKIP_DIRS for p in rel.split("/")[:-1])


def iter_source_files_at_commit(
    repo: str | Path,
    commit: str,
    languages: Iterable[str] = DEFAULT_LANGUAGES,
    include_generated: bool = False,
) -> Iterator[SourceFile]:
    """Yield source files as they were at `commit`, read from git objects without touching the worktree."""
    languages = frozenset(languages)
    listing = subprocess.run(
        ["git", "-C", str(repo), "ls-tree", "-r", "-z", "--long", commit], capture_output=True, check=True
    ).stdout.decode("utf-8", errors="surrogateescape")
    wanted: list[tuple[str, str]] = []
    for entry in listing.split("\0"):
        if not entry:
            continue
        meta, path = entry.split("\t", 1)
        mode, kind, obj, size = meta.split()
        # Skip symlinks (120000) and submodules (160000 / commit objects).
        if kind != "blob" or mode == "120000" or size == "-" or int(size) > MAX_FILE_BYTES:
            continue
        if _skipped_dir(path) or detect_language(path) not in languages:
            continue
        wanted.append((path, obj))
    wanted.sort()
    proc = subprocess.Popen(
        ["git", "-C", str(repo), "cat-file", "--batch"], stdin=subprocess.PIPE, stdout=subprocess.PIPE
    )
    assert proc.stdin is not None and proc.stdout is not None
    try:
        for path, obj in wanted:
            proc.stdin.write(f"{obj}\n".encode())
            proc.stdin.flush()
            header = proc.stdout.readline().split()
            size = int(header[2])
            data = proc.stdout.read(size)
            proc.stdout.read(1)  # trailing newline
            text = _decode_source(data)
            if text is None or not text.strip():
                continue
            if not include_generated and is_probably_generated(text):
                continue
            yield SourceFile(path=path, language=detect_language(path) or "", text=text)
    finally:
        proc.stdin.close()
        proc.wait()


def iter_source_files(
    root: str | Path,
    languages: Iterable[str] = DEFAULT_LANGUAGES,
    include_generated: bool = False,
) -> Iterator[SourceFile]:
    """Yield source files under `root` in a deterministic order."""
    root = Path(root).resolve()
    languages = frozenset(languages)
    rel_paths = _git_files(root)
    if rel_paths is None:
        rel_paths = list(_walk_files(root))
    for rel in sorted(set(rel_paths)):
        if _skipped_dir(rel):
            continue
        language = detect_language(rel)
        if language not in languages:
            continue
        text = read_source(root / rel)
        if text is None or not text.strip():
            continue
        if not include_generated and is_probably_generated(text):
            continue
        yield SourceFile(path=rel, language=language, text=text)
