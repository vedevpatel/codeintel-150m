def test_chunks_cover_every_code_line():
    chunker = Chunker()
    for source in iter_source_files(SAMPLE_REPO):
        chunks = chunker.chunk(source)
        covered = set()
        for c in chunks:
            covered.update(range(c.start_line, c.end_line + 1))
        lines = source.text.splitlines()
        uncovered = [i for i, line in enumerate(lines, 1) if line.strip() and i not in covered]
        # Only isolated single lines between definitions may be dropped (min_module_lines=2).
        assert len(uncovered) <= 3, (source.path, uncovered)
        assert len({c.chunk_id for c in chunks}) == len(chunks)


def test_chunk_text_has_path_header_and_skeleton():
    source = next(f for f in iter_source_files(SAMPLE_REPO) if f.path == "inventory/models.py")
    chunks = {(c.kind, c.symbol): c for c in Chunker().chunk(source)}
    method = chunks[("method", "Inventory.remove")]
    assert method.text.startswith("# inventory/models.py::Inventory.remove\n")
    assert method.text.splitlines()[1].startswith("def remove(")  # dedented
    skeleton = chunks[("skeleton", "Inventory")]
    assert "def remove(self, sku: str, quantity: int) -> Item: ..." in skeleton.text
    assert "raise OutOfStockError" not in skeleton.text


def test_long_definitions_are_windowed():
    body = "\n".join(f"    x{i} = {i}" for i in range(300))
    source = SourceFile("big.py", "python", f"def big():\n{body}\n    return 0\n")
    chunks = Chunker(ChunkerConfig(max_lines=100, window_overlap=10)).chunk(source)
    parts = [c for c in chunks if c.symbol == "big"]
    assert len(parts) == 4
    assert all("(part " in c.text.splitlines()[0] for c in parts)
    assert parts[0].start_line == 1 and parts[-1].end_line == 302
    assert parts[1].start_line == parts[0].end_line - 9


