def test_index_roundtrip_and_embedding_cache(tmp_path, hashing_model):
    cache = EmbeddingCache(tmp_path / "cache", hashing_model.fingerprint, hashing_model.dim)
    index = build_index(SAMPLE_REPO, model=hashing_model, cache=cache)
    first = hashing_model.encoded
    assert first == len({c.text for c in index.chunks})
    index.save(tmp_path / "idx")
    loaded = CodeIndex.load(tmp_path / "idx")
    assert [c.chunk_id for c in loaded.chunks] == [c.chunk_id for c in index.chunks]
    np.testing.assert_allclose(loaded.embeddings, index.embeddings)
    # Rebuilding hits the cache for every chunk.
    build_index(SAMPLE_REPO, model=hashing_model, cache=cache)
    assert hashing_model.encoded == first


