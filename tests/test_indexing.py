def test_index_roundtrip_and_embedding_cache(tmp_path, hashing_model):
    cache = EmbeddingCache(tmp_path / "cache", hashing_model.fingerprint, hashing_model.dim)
    index = build_index(SAMPLE_REPO, model=hashing_model, cache=cache)
    first = hashing_model.encoded
    assert first == len({c.text for c in index.chunks})
    index.save(tmp_path / "idx")
    loaded = CodeIndex.load(tmp_path / "idx")
    assert [c.chunk_id for c in loaded.chunks] == [c.chunk_id for c in index.chunks]
    np.testing.assert_allclose(loaded.embeddings, index.embeddings)
    # Rebuilding hits the cache for every chunk.
    build_index(SAMPLE_REPO, model=hashing_model, cache=cache)
    assert hashing_model.encoded == first


def test_encode_cached_dedupes_within_call(hashing_model):
    out = encode_documents_cached(hashing_model, ["a b", "c d", "a b"])
    assert hashing_model.encoded == 2
    np.testing.assert_allclose(out[0], out[2])


def test_read_files_at_commit(git_repo):
    head = git(git_repo, "rev-parse", "HEAD").strip()
    parent = git(git_repo, "rev-parse", "HEAD~1").strip()
    old = {f.path: f.text for f in iter_source_files_at_commit(git_repo, parent)}
    new = {f.path: f.text for f in iter_source_files_at_commit(git_repo, head)}
    assert set(old) == {"pkg/math_utils.py"}
    assert "factor == 0" not in old["pkg/math_utils.py"] and "factor == 0" in new["pkg/math_utils.py"]


def test_mine_commits_maps_diff_to_pre_change_symbols(git_repo):
    examples = list(mine_commits(git_repo))
    assert len(examples) == 1  # "initial import" has no parent
    ex = examples[0]
    assert ex.gold_files == ["pkg/math_utils.py"]
    assert [c.symbol for c in ex.changed_chunks] == ["scale"]
    assert "factor == 0" not in ex.changed_chunks[0].text  # positive is the pre-change code
    case = ex.to_case("repo")
    assert case.commit == git(git_repo, "rev-parse", "HEAD~1").strip()
    assert case.gold_symbols == ["pkg/math_utils.py::scale"]
    pair = ex.to_pairs("repo")[0]
    assert pair.task == "issue2code" and pair.query.startswith("Fix scale")


