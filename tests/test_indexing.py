def test_repository_walk_skips_vendored_generated_and_binary(tmp_path):
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "app.py").write_text("def main():\n    return 1\n")
    (tmp_path / "src" / "types.d.ts").write_text("export declare const x: number;\n")
    (tmp_path / "src" / "gen.py").write_text("# @generated by protoc\nX = 1\n")
    (tmp_path / "src" / "min.js").write_text("var a=" + "1+" * 2000 + "1;\n")
    (tmp_path / "src" / "blob.py").write_bytes(b"\x00\x01binary")
    (tmp_path / "node_modules" / "lib").mkdir(parents=True)
    (tmp_path / "node_modules" / "lib" / "index.js").write_text("module.exports = 1;\n")
    paths = [f.path for f in iter_source_files(tmp_path)]
    assert paths == ["src/app.py"]


